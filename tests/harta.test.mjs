// Teste „Harta ramificațiilor” + legătura NOMIA (v2.1.0).
// Rulare: node tests/harta.test.mjs   (Playwright + Chromium; PW_ROOT/CHROMIUM_PATH opționale)
import {createRequire} from 'module';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const require = createRequire(process.env.PW_ROOT || import.meta.url);
const {chromium} = require('playwright');
const HERE = path.dirname(fileURLToPath(import.meta.url));
const URL_APP = 'file://' + path.join(HERE, '..', 'index.html');
let pass = 0, fail = 0;
const ok = (c, n, i) => { if (c) { pass++; console.log('  ok   ' + n); } else { fail++; console.log('  FAIL ' + n + (i === undefined ? '' : ' ' + JSON.stringify(i).slice(0, 300))); } };
const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const net = [], errs = [];
const ctx = await browser.newContext({viewport: {width: 1280, height: 800}, locale: 'ro-RO'});
await ctx.route(/^https?:/, r => { net.push(r.request().url()); r.abort(); });
const page = await ctx.newPage();
page.on('pageerror', e => errs.push(e.message));
page.on('console', m => { if (/Content Security Policy|Refused to/i.test(m.text())) errs.push(m.text()); });
await page.goto(URL_APP);
await page.waitForFunction(() => window.__piCale && typeof go === 'function');
console.log('PrintreInteligente — harta ramificațiilor');
await page.evaluate(() => window.__piCale.open());
await page.waitForSelector('.pc-map');
ok(await page.locator('.pc-fam').count() === 5, 'harta are 5 familii');
ok(await page.locator('.pc-chip').count() === 17, 'harta are 17 scenarii');
const nomia = await page.locator('.pc-lnk').getAttribute('href');
ok(nomia === 'https://chiuta.github.io/NOMIA/', 'legătura spre NOMIA', nomia);
ok((await page.locator('.pc-lnk').getAttribute('rel')).includes('noopener'), 'NOMIA: rel=noopener');
const before = net.length;
await page.locator('.pc-chip').first().click();
await page.waitForTimeout(600);
ok(await page.evaluate(() => (window.__piCale.state().seen.A || 0) >= 1), 'clic pe A1 deschide scenariul A (marcat parcurs)');
ok(net.length === before, 'nicio cerere în rețea la deschiderea hărții/scenariului', net.slice(before));
await page.evaluate(() => window.__piCale.open());
await page.waitForSelector('.pc-map');
ok(await page.locator('.pc-fam.pc-seen').count() === 1, 'familia A e marcată ca parcursă');
await page.locator('.pc-chip').nth(16).click();
await page.waitForTimeout(600);
ok(await page.evaluate(() => !!document.getElementById('sub-e2')), 'clic pe E2 duce la Epilog, unde există #sub-e2');
ok(errs.length === 0, 'fără erori JS/CSP', errs);
await browser.close();
console.log(pass + ' ok, ' + fail + ' eșuate');
process.exit(fail ? 1 : 0);
